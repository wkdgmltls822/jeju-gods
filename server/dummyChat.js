// 데모 채팅: AI 키가 없거나 한도가 찼을 때 쓰는 "미리 준비한 답"입니다.
// 외부 API 를 전혀 부르지 않고, 신 데이터(src/data/gods.js)와 키워드 규칙만으로 답합니다.
// 날씨·관람객 같은 실시간 정보는 지어내지 않고 "지금은 확인할 수 없다"고 말합니다.

export function dummyReply({ god, message = '' }) {
  const has = (...words) => words.some((w) => message.includes(w))
  const place = god.places?.[0]

  if (has('안녕', '반가', '누구')) {
    return `나는 ${god.name}, ${god.role}이다. 잘 왔구나. 내 이야기(${god.tale})가 궁금하면 언제든 물어보려무나.`
  }
  if (has('날씨', '비', '바람', '덥', '춥', '맑')) {
    return `오늘 하늘이 어떤지는 지금 내가 직접 살필 수 없구나. 실시간 날씨는 AI가 연결되어야 알려 줄 수 있단다. 홈 화면의 날씨 배지를 먼저 보고 오려무나.`
  }
  if (has('관람', '붐비', '사람', '인원', '많')) {
    return `얼마나 붐비는지는 지금 확인할 수 없구나. 별자리 페이지 아래의 서귀포 관람객 그래프에서 달마다 살펴볼 수 있단다.`
  }
  if (has('장소', '어디', '가볼', '가면', '여행', '추천')) {
    return place
      ? `전해지기로는 내 이야기와 이어진 곳으로 ${place} 일대가 있단다. 별자리 페이지에서 내 별을 누르면 이어지는 장소를 볼 수 있어.`
      : `내 이야기와 이어진 장소는 별자리 페이지에서 내 별을 누르면 볼 수 있단다.`
  }
  if (has('이야기', '설화', '본풀이', '전설', '들려')) {
    return `${god.text} 내 이야기는 「${god.tale}」로 전해지고 있단다.`
  }
  return `그런 것은 내 이야기에서 들어 본 적이 없구나. 없는 것을 지어내어 말하지는 않으마. 내 이야기나 이어진 장소를 물어보면 아는 만큼 답해 주겠다.`
}
